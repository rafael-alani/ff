import { FONT_DEFINITIONS } from "@/lib/font-definitions"
import {
  buildThemeForPreset,
  DEFAULT_CONFIG,
  designSystemConfigSchema,
  POINTER_CURSOR_SELECTOR,
  type DesignSystemConfig,
} from "@/registry/config"

import {
  buildAdvancedCss,
  DEFAULT_ADVANCED,
  validateAdvanced,
  type AdvancedSettings,
} from "./advanced"

/** Complete, portable Form & Field state. Essentials remain the official schema. */
export type FormFieldDocument = {
  version: 1
  essentials: DesignSystemConfig
  advanced: AdvancedSettings
}

export const DEFAULT_DOCUMENT: FormFieldDocument = {
  version: 1,
  essentials: { ...DEFAULT_CONFIG, item: "preview-02" },
  advanced: { ...DEFAULT_ADVANCED, tokens: { light: {}, dark: {} } },
}

/** Import and save boundaries reject invalid fields rather than silently resetting. */
export function parseDocument(input: unknown): FormFieldDocument {
  if (!input || typeof input !== "object" || Array.isArray(input)) {
    throw new Error("A Form & Field preset must be a JSON object.")
  }
  const value = input as Record<string, unknown>
  if (value.version !== 1) {
    throw new Error("This Form & Field preset version is not supported.")
  }
  if (
    Object.keys(value).some(
      (key) => !["version", "essentials", "advanced"].includes(key)
    )
  ) {
    throw new Error("The preset contains an unknown top-level field.")
  }
  const essentials = designSystemConfigSchema.parse(value.essentials)
  if (
    essentials.item !== undefined &&
    !/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,127}$/.test(essentials.item)
  ) {
    throw new Error("The selected preview item must be a registry item name.")
  }
  const advanced = validateAdvanced(value.advanced)
  return { version: 1, essentials, advanced }
}

export function getDocumentFontDependencies(
  document: FormFieldDocument
): string[] {
  const names = new Set([
    document.essentials.font,
    document.essentials.fontHeading === "inherit"
      ? document.essentials.font
      : document.essentials.fontHeading,
  ])
  return FONT_DEFINITIONS.filter((font) => names.has(font.name)).map(
    (font) => font.dependency
  )
}

function cssRule(selector: string, values: Record<string, string | undefined>) {
  const declarations = Object.entries(values)
    .filter(([, value]) => value !== undefined)
    .map(([key, value]) => `  --${key}: ${value};`)
    .join("\n")
  return `${selector} {\n${declarations}\n}`
}

/** The same generator is used by disk saves and production source downloads. */
export function generateThemeCss(input: FormFieldDocument): string {
  const document = parseDocument(input)
  const { essentials, advanced } = document
  const theme = buildThemeForPreset(essentials)
  const bodyFont = FONT_DEFINITIONS.find(
    (font) => font.name === essentials.font
  )
  const headingFont =
    essentials.fontHeading === "inherit"
      ? bodyFont
      : FONT_DEFINITIONS.find((font) => font.name === essentials.fontHeading)
  const imports = getDocumentFontDependencies(document)
    .map((dependency) => `@import "${dependency}";`)
    .join("\n")
  return (
    [
      "/* Generated by Form & Field. Durable custom rules belong in overrides.css. */",
      imports,
      cssRule(":root", {
        ...theme.cssVars?.theme,
        ...theme.cssVars?.light,
        "font-sans": bodyFont?.family,
        "font-heading": headingFont?.family,
        "font-mono": "ui-monospace, SFMono-Regular, Menlo, monospace",
        "font-serif": "ui-serif, Georgia, serif",
        ...(bodyFont
          ? { [bodyFont.registryVariable.slice(2)]: bodyFont.family }
          : {}),
      }),
      cssRule(".dark", theme.cssVars?.dark ?? {}),
      essentials.pointer
        ? `${POINTER_CURSOR_SELECTOR} { cursor: pointer; }`
        : "",
      buildAdvancedCss(advanced),
    ]
      .filter(Boolean)
      .join("\n\n") + "\n"
  )
}
